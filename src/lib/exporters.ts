// Client-side PDF & Excel exporters.
//
// Heavy dependencies (jspdf, xlsx) are lazy-loaded so the app shell stays fast;
// they only download when a user actually exports a report.
//
// Two families live here:
//   1. The per-student course report (lecturer's working document).
//   2. The institution-wide attendance workbook (brief §7): described by a
//      ReportDataset so the screen, the spreadsheet and the printed report are
//      guaranteed to show the same numbers — they are built from one payload.

import type { CourseReportData, ExportOptions } from "./export-types";
import type {
  CourseReport,
  CourseReportRow,
  CoursesReport,
  CourseSessionStat,
  ReportFilters,
} from "./types";

function safeFileName(code: string): string {
  return code.replace(/[^a-z0-9]+/gi, "_").replace(/^_+|_+$/g, "") || "course";
}

function stamp(): string {
  return new Date().toISOString().slice(0, 10);
}

export async function exportPDF(report: CourseReportData, options: ExportOptions = {}) {
  const [{ default: jsPDF }, { default: autoTable }] = await Promise.all([
    import("jspdf"),
    import("jspdf-autotable"),
  ]);
  const { course, totalSessions, students } = report;
  const institution = options.institutionName ?? "SLAMS";

  const doc = new jsPDF();

  doc.setFont("helvetica", "bold");
  doc.setFontSize(16);
  doc.text(`${institution} — Attendance Report`, 14, 18);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(11);
  doc.text(`Course: ${course.code} — ${course.title}`, 14, 28);
  doc.text(
    `Level: ${course.level}   Units: ${course.units}   Sessions held: ${totalSessions}`,
    14,
    35,
  );
  doc.text(`Generated: ${new Date().toLocaleString()}`, 14, 42);

  autoTable(doc, {
    startY: 50,
    head: [["#", "Name", "Matric", "Attended", "Total", "%", "Devices"]],
    body: students.map((s, i) => [
      String(i + 1),
      s.name,
      s.matricNo,
      String(s.attended),
      String(totalSessions),
      `${s.percentage}%`,
      s.devices > 1 ? `${s.devices} (!)` : String(s.devices),
    ]),
    styles: { fontSize: 10 },
    headStyles: { fillColor: [15, 92, 75] },
  });

  doc.save(`attendance-${safeFileName(course.code)}.pdf`);
}

export async function exportExcel(report: CourseReportData, _options: ExportOptions = {}) {
  const XLSX = await import("xlsx");
  const { course, totalSessions, students } = report;
  void course;
  const rows = students.map((s, i) => ({
    "#": i + 1,
    Name: s.name,
    Matric: s.matricNo,
    Attended: s.attended,
    Total: totalSessions,
    "Attendance %": s.percentage,
    Devices: s.devices,
  }));
  const ws = XLSX.utils.json_to_sheet(rows);
  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, ws, "Attendance");
  XLSX.writeFile(wb, `attendance-${safeFileName(course.code)}.xlsx`);
}

// ─── Institution attendance workbook (brief §7) ────────────────────────────

export interface CoursesWorkbookOptions {
  institutionName: string;
  threshold: number;
  /** Screens and spreadsheets must agree on the period label. */
  sessionName?: string;
  semesterName?: string;
  generatedBy?: string;
}

/**
 * Build the multi-sheet Excel workbook from the *same* payload the table shows:
 *
 *   Report Info  — institution, period, applied filters, generation metadata
 *   Summary      — one row per course + a weighted totals row
 *   Students     — optional per-student detail (supplied separately)
 *   Sessions     — optional per-lecture detail (supplied separately)
 *
 * Every sheet is generated from server-computed values, so a downloaded report
 * can never disagree with the screen it came from (brief §7 "the export
 * functions must use the current filters").
 */
export async function buildCoursesWorkbook(
  report: CoursesReport,
  options: CoursesWorkbookOptions,
  extra: {
    students?: Array<Record<string, string | number>>;
    sessions?: Array<Record<string, string | number>>;
  } = {},
) {
  const XLSX = await import("xlsx");
  const wb = XLSX.utils.book_new();
  const f = report.meta.filters;

  const info: Array<[string, string | number]> = [
    ["Institution", options.institutionName],
    ["Report", "Course attendance summary"],
    ["Academic session", options.sessionName ?? "—"],
    ["Semester", options.semesterName ?? "—"],
    ["Courses included", report.totals.courses],
    ["Generated", new Date(report.meta.generatedAt).toLocaleString()],
    ["Generated by", options.generatedBy ?? "—"],
    ["Calculation", "Opportunity-weighted: attended ÷ expected opportunities"],
    ["At-risk threshold", `${options.threshold}%`],
  ];
  const filterEntries = Object.entries(f).filter(
    ([key, value]) =>
      value !== undefined && value !== null && value !== "" && key !== "page" && key !== "pageSize",
  );
  if (filterEntries.length === 0) {
    info.push(["Filters applied", "None (all courses)"]);
  } else {
    for (const [key, value] of filterEntries) {
      const shown =
        key === "from" || key === "to" ? new Date(Number(value)).toLocaleString() : String(value);
      info.push([`Filter · ${key}`, shown]);
    }
  }
  const infoSheet = XLSX.utils.aoa_to_sheet([["Field", "Value"], ...info]);
  infoSheet["!cols"] = [{ wch: 26 }, { wch: 62 }];
  XLSX.utils.book_append_sheet(wb, infoSheet, "Report Info");

  const summaryRows = report.rows.map((r) => ({
    "Course Code": r.code,
    "Course Title": r.title,
    Department: r.departmentName ?? r.departmentCode ?? "—",
    Faculty: r.facultyName ?? "—",
    Lecturer: r.lecturerName ?? "Unassigned",
    Level: r.level,
    "Registered Students": r.enrolled,
    "Classes Held": r.classesHeld,
    "Classes Attended (avg/student)": r.classesAttended,
    Present: r.present,
    Absent: r.absent,
    Late: r.late,
    Excused: r.excused,
    "Attendance %": r.rate ?? "—",
    Target: options.threshold,
    Status:
      r.health === "good"
        ? "On track"
        : r.health === "watch"
          ? "Watch"
          : r.health === "at-risk"
            ? "At risk"
            : r.health === "critical"
              ? "Critical"
              : "No lectures yet",
  }));
  summaryRows.push({
    "Course Code": "TOTAL",
    "Course Title": `${report.totals.courses} courses`,
    Department: "",
    Faculty: "",
    Lecturer: "",
    Level: "",
    "Registered Students": report.totals.enrolled,
    "Classes Held": report.totals.classesHeld,
    "Classes Attended (avg/student)": report.totals.classesAttended,
    Present: report.totals.present,
    Absent: report.totals.absent,
    Late: report.totals.late,
    Excused: report.totals.excused,
    "Attendance %": report.totals.rate ?? "—",
    Target: options.threshold,
    Status: "Weighted average",
  });
  const summarySheet = XLSX.utils.json_to_sheet(summaryRows);
  summarySheet["!cols"] = [
    { wch: 12 },
    { wch: 34 },
    { wch: 24 },
    { wch: 22 },
    { wch: 22 },
    { wch: 8 },
    { wch: 10 },
    { wch: 10 },
    { wch: 12 },
    { wch: 9 },
    { wch: 9 },
    { wch: 8 },
    { wch: 9 },
    { wch: 11 },
    { wch: 8 },
    { wch: 16 },
  ];
  summarySheet["!autofilter"] = {
    ref: XLSX.utils.encode_range({ s: { r: 0, c: 0 }, e: { r: summaryRows.length, c: 15 } }),
  };
  XLSX.utils.book_append_sheet(wb, summarySheet, "Summary");

  if (extra.sessions?.length) {
    const sheet = XLSX.utils.json_to_sheet(extra.sessions);
    XLSX.utils.book_append_sheet(wb, sheet, "Lectures");
  }
  if (extra.students?.length) {
    const sheet = XLSX.utils.json_to_sheet(extra.students);
    XLSX.utils.book_append_sheet(wb, sheet, "Students");
  }

  return wb;
}

/** Download the institution workbook (the button on the All Courses page). */
export async function exportCoursesExcel(
  report: CoursesReport,
  options: CoursesWorkbookOptions & {
    sessions?: CourseSessionStat[];
    students?: Array<Record<string, string | number>>;
  },
) {
  const XLSX = await import("xlsx");
  const wb = await buildCoursesWorkbook(report, options, {
    sessions: options.sessions?.map((s) => ({
      Lecture: new Date(s.startedAt).toLocaleDateString(),
      Topic: s.topic ?? "",
      Expected: s.expected,
      Present: s.present,
      Late: s.late,
      Excused: s.excused,
      Absent: s.absent,
      "Attendance %": s.rate ?? "—",
    })),
    students: options.students,
  });
  XLSX.writeFile(wb, `SLAMS_Attendance_${stamp()}.xlsx`);
}

/** Convenience for a single-course export from the detail page. */
export function courseRowToWorkbookRow(row: CourseReportRow) {
  return {
    "Course Code": row.code,
    "Course Title": row.title,
    Students: row.enrolled,
    "Classes Held": row.classesHeld,
    Present: row.present,
    Absent: row.absent,
    Late: row.late,
    "Attendance %": row.rate ?? "—",
  };
}

// ─── One course, three sheets (course detail page, brief §5/§7) ─────────────

export interface CourseReportExcelOptions {
  institutionName: string;
  threshold: number;
  filters?: ReportFilters;
}

/**
 * The working document for a single course: what was held, who came, and what
 * each student's record looks like. Everything is taken from the server's
 * course report, so the spreadsheet repeats the screen exactly.
 */
export async function exportCourseReportExcel(
  report: CourseReport,
  lectures: CourseSessionStat[],
  options: CourseReportExcelOptions,
) {
  const XLSX = await import("xlsx");
  const wb = XLSX.utils.book_new();
  const { course, counts } = report;

  const info: Array<[string, string | number]> = [
    ["Institution", options.institutionName],
    ["Course", `${course.code} — ${course.title}`],
    ["Department", course.departmentName ?? "—"],
    ["Faculty", course.facultyName ?? "—"],
    ["Lecturer", course.lecturerName ?? "Unassigned"],
    ["Level / units", `${course.level} · ${course.units} units`],
    ["Semester", report.term?.name ?? "All periods"],
    ["Registered students", report.students.length],
    ["Lectures held", report.totalSessions],
    [
      "Present / late / excused / absent",
      `${counts.present} / ${counts.late} / ${counts.excused} / ${counts.absent}`,
    ],
    ["Overall attendance", report.weightedRate === null ? "—" : `${report.weightedRate}%`],
    [
      "Mean of student percentages",
      report.meanOfStudents === null ? "—" : `${report.meanOfStudents}%`,
    ],
    ["Target", `${options.threshold}%`],
    ["Generated", new Date().toLocaleString()],
  ];
  for (const [key, value] of Object.entries(options.filters ?? {})) {
    if (value === undefined || value === null || value === "") continue;
    info.push([
      `Filter · ${key}`,
      key === "from" || key === "to" ? new Date(Number(value)).toLocaleString() : String(value),
    ]);
  }
  const infoSheet = XLSX.utils.aoa_to_sheet([["Field", "Value"], ...info]);
  infoSheet["!cols"] = [{ wch: 30 }, { wch: 60 }];
  XLSX.utils.book_append_sheet(wb, infoSheet, "Course Info");

  const studentRows = report.students.map((s, i) => ({
    "#": i + 1,
    Name: s.name,
    "Matric No.": s.matricNo,
    Present: s.present,
    Absent: s.absent,
    Late: s.late,
    Excused: s.excused,
    Attended: s.attended,
    Expected: s.expected,
    "Attendance %": s.percentage,
    Status:
      s.percentage >= options.threshold
        ? "On track"
        : s.attended === 0
          ? "Never attended"
          : "Below target",
    Devices: s.devices,
  }));
  const studentSheet = XLSX.utils.json_to_sheet(studentRows);
  studentSheet["!cols"] = [
    { wch: 4 },
    { wch: 28 },
    { wch: 16 },
    { wch: 9 },
    { wch: 8 },
    { wch: 7 },
    { wch: 9 },
    { wch: 10 },
    { wch: 10 },
    { wch: 13 },
    { wch: 15 },
    { wch: 9 },
  ];
  XLSX.utils.book_append_sheet(wb, studentSheet, "Students");

  const lectureRows = lectures.map((l, i) => ({
    "#": i + 1,
    Date: new Date(l.startedAt).toLocaleDateString(),
    Time: new Date(l.startedAt).toLocaleTimeString(),
    Topic: l.topic ?? "",
    Expected: l.expected,
    Present: l.present,
    Late: l.late,
    Excused: l.excused,
    Absent: l.absent,
    "Attendance %": l.rate ?? "—",
  }));
  const lectureSheet = XLSX.utils.json_to_sheet(
    lectureRows.length ? lectureRows : [{ Note: "No lectures recorded in this period" }],
  );
  XLSX.utils.book_append_sheet(wb, lectureSheet, "Lectures");

  XLSX.writeFile(wb, `SLAMS_Course_${safeFileName(course.code)}_${stamp()}.xlsx`);
}
